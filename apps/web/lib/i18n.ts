export type UiText = WidenStrings<typeof UI_TEXT.en>;

export function isUiLanguage(value: unknown): value is UiLanguage {
  return value === "en" || value === "zh";
}

export function textForLanguage(language: UiLanguage): UiText {
  return UI_TEXT[language] as UiText;
}
